export const CATEGORIES: CategoryConfig[] = [phones, laptops, tvs, headphones, tablets, monitors];

export const CATEGORY_SLUGS = CATEGORIES.map((c) => c.slug);

export function getCategory(slug: string): CategoryConfig | undefined {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function requireCategory(slug: CategorySlug): CategoryConfig {
  const c = getCategory(slug);
  if (!c) throw new Error(`Unknown category: ${slug}`);
  return c;
}

export function isCategorySlug(slug: string): slug is CategorySlug {
  return CATEGORY_SLUGS.includes(slug as CategorySlug);
}
